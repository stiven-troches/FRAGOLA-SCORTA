  estado               text NOT NULL CHECK (estado IN ('recibida','enviada','aprobada','rechazada','cerrada')),
  en_garantia          bigint,
  resultado            text,
  decision             jsonb,                               -- {tipo, fecha, usuario, nota, reembolso{total, credito, pagos[]}}
  decision_tipo        text GENERATED ALWAYS AS (decision->>'tipo') STORED,
  respuesta_proveedor  jsonb,
  nota                 text NOT NULL DEFAULT '',
  usuario              text,
  user_id              text,
  extra                jsonb,
  seq                  bigint GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (company_id, id),
  FOREIGN KEY (company_id, sale_id) REFERENCES sales(company_id, id),
  FOREIGN KEY (company_id, customer_id) REFERENCES customers(company_id, id),
  FOREIGN KEY (company_id, supplier_id) REFERENCES suppliers(company_id, id)
);
CREATE INDEX warranties_estado_idx ON warranties (company_id, estado);
CREATE INDEX warranties_sale_idx ON warranties (company_id, sale_id);

CREATE TABLE warranty_history (
  company_id   text NOT NULL,
  warranty_id  text NOT NULL,
  seq          integer NOT NULL,
  estado       text NOT NULL,
  fecha        timestamptz,
  usuario      text,
  user_id      text,
  nota         text,
  extra        jsonb,
  PRIMARY KEY (company_id, warranty_id, seq),
  FOREIGN KEY (company_id, warranty_id) REFERENCES warranties(company_id, id) ON DELETE CASCADE
);

