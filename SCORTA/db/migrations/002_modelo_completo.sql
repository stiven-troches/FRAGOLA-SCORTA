--   * la lista REAL de medios de pago (efectivo, transferencia, tarjeta, Nequi, Daviplata y los
--     tres medios que no mueven dinero: crédito, anticipo de separado y saldo a favor);
--   * pagos divididos (`sale_payments`, un renglón por medio con su monto), IVA y descuentos;
