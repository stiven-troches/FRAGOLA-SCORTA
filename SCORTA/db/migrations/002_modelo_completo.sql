-- Pagos efectivos de cada venta: los renglones de sale_payments y, para ventas antiguas sin
-- `payments`, su payment_method por el total (igual que salePayments() de sale-pricing.mjs).
CREATE VIEW sale_payment_lines AS
  SELECT company_id, sale_id, line_no, method, amount, false AS derived FROM sale_payments
  UNION ALL
  SELECT s.company_id, s.id, 0, s.payment_method, s.total, true
  FROM sales s JOIN payment_methods m ON m.code = s.payment_method
  WHERE NOT EXISTS (SELECT 1 FROM sale_payments p WHERE p.company_id = s.company_id AND p.sale_id = s.id);

